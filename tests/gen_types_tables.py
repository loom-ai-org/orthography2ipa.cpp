#!/usr/bin/env python3
"""Generate src/types_tables.inc from the reference types module.

The string enums (OrthographyKind / QualityTier / ScriptType / AncestorRole /
GraphemePosition / InheritanceMode / AuditConclusion), the FIELD_INHERITANCE
manifest and the LanguageSpec declared-field list are DATA: transcribed from
the reference, never retyped. Run after any change to types.py:

    /home/flavio/.venvs/piper/bin/python3 tests/gen_types_tables.py
"""
import os
import pathlib
import sys
from dataclasses import fields as dc_fields

HERE = pathlib.Path(__file__).resolve().parent
CPP_ROOT = HERE.parent
reference = os.environ.get("O2I_PYTHON_ROOT") or str(CPP_ROOT.parent / "orthography2ipa")
sys.path.insert(0, reference)

import orthography2ipa.types as T  # noqa: E402


def cstr(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def enum_table(name, enum_cls, docs):
    lines = [f"// {docs}",
             f"static const std::pair<const char*, const char*> {name}[] {{"]
    for member in enum_cls:
        lines.append("    {" + cstr(member.name) + ", " + cstr(member.value) + "},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parts = [
        "// GENERATED by tests/gen_types_tables.py from orthography2ipa/types.py.",
        "// Do not edit: regenerate after any change to the reference.",
        "",
        enum_table("kOrthographyKind", T.OrthographyKind,
                   "types.py OrthographyKind(str, Enum)."),
        enum_table("kQualityTier", T.QualityTier,
                   "types.py QualityTier(str, Enum)."),
        enum_table("kScriptType", T.ScriptType,
                   "types.py ScriptType(str, Enum)."),
        enum_table("kAncestorRole", T.AncestorRole,
                   "types.py AncestorRole(str, Enum)."),
        enum_table("kInheritanceMode", T.InheritanceMode,
                   "types.py InheritanceMode(str, Enum)."),
        enum_table("kAuditConclusion", T.AuditConclusion,
                   "types.py AuditConclusion(str, Enum)."),
        enum_table("kGraphemePosition", T.GraphemePosition,
                   "types.py GraphemePosition(str, Enum) \u2014 the 45 positional keys."),
        "// types.py FIELD_INHERITANCE: every LanguageSpec field -> the mode the",
        "// loader resolves it with; fields_missing_inheritance_decision()",
        "// diff-checks the manifest against the declared field list.",
        "static const std::pair<const char*, const char*> kFieldInheritance[] {",
    ]
    for field_name, mode in T.FIELD_INHERITANCE.items():
        parts.append("    {" + cstr(field_name) + ", " + cstr(mode.value) + "},")
    parts.append("};\n")
    parts.append("")
    parts.append("// types.py fields(LanguageSpec): the declared field names, in")
    parts.append("// declaration order \u2014 the other half of the diff-check.")
    parts.append("static const std::pair<const char*, const char*> kSpecFields[] {")
    for field in dc_fields(T.LanguageSpec):
        parts.append("    {" + cstr(field.name) + ', ""},')
    parts.append("};\n")
    out = CPP_ROOT / "src" / "types_tables.inc"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}: modes={len(T.InheritanceMode)} roles={len(T.AncestorRole)} "
          f"positions={len(T.GraphemePosition)} fields={len(T.FIELD_INHERITANCE)} "
          f"spec_fields={len(dc_fields(T.LanguageSpec))}")


if __name__ == "__main__":
    main()
